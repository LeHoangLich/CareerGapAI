import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { openView, register } from './helpers';

test('Fake writing and matching run through workers; private CV application preserves exact PDF snapshot', async ({ browser, baseURL }) => {
  test.setTimeout(150000);
  const recruiterContext = await browser.newContext({ baseURL });
  const candidateContext = await browser.newContext({ baseURL });
  const recruiter = await recruiterContext.newPage(), candidate = await candidateContext.newPage();
  try {
    const title = `UI worker React ${randomUUID()}`;
    await register(recruiter, 'Recruiter');
    await openView(recruiter, 'recruiter-jobs');
    const manager = recruiter.locator('.recruiter-jobs');
    await openView(recruiter, 'recruiter-company');
    await manager.getByLabel('Tên công ty', { exact: true }).fill(`UI synthetic ${randomUUID()}`);
    await manager.getByRole('button', { name: 'Tạo công ty', exact: true }).click();
    await expect(manager.getByRole('status')).toContainText('Hồ sơ công ty đã được lưu.');
    await openView(recruiter, 'recruiter-jobs');
    const editor = manager.locator('.editor-form').last();
    await editor.getByLabel('Chức danh', { exact: true }).fill(title);
    await editor.getByLabel('Mô tả công việc', { exact: true }).fill('Build React tools.');
    await editor.getByLabel('Yêu cầu và kỹ năng', { exact: true }).fill('Bắt buộc: React\nƯu tiên: TypeScript');
    await editor.getByRole('button', { name: 'Tạo tin nháp', exact: true }).click();
    const job = manager.locator('.job-card').filter({ hasText: title });
    const requirements = job.locator('.job-revision-review');
    await requirements.getByRole('button', { name: 'Tách yêu cầu từ JD (local)', exact: true }).click();
    await expect(requirements.getByRole('checkbox')).toHaveCount(2);
    await requirements.getByRole('button', { name: 'Xác nhận yêu cầu JD', exact: true }).click();
    await expect(requirements).toContainText('Đã xác nhận');
    await job.getByRole('button', { name: 'Công khai', exact: true }).click();
    await register(candidate);
    await openView(candidate, 'cv-builder');
    const builder = candidate.locator('.resume-builder');
    await builder.getByLabel('Tên hiển thị *', { exact: true }).fill('Ứng viên synthetic worker');
    await builder.getByLabel('Giới thiệu', { exact: true }).fill('Built React tools.');
    await builder.getByLabel('Kỹ năng, mỗi dòng một mục', { exact: true }).fill('React\nTypeScript');
    await builder.getByRole('button', { name: 'Tạo bản xem trước PDF', exact: true }).click();
    await expect(builder.getByTitle('Xem trước CV PDF')).toBeVisible({ timeout: 20000 });
    await builder.getByRole('button', { name: 'Lưu thành phiên bản CV', exact: true }).click();
    await expect(builder.getByRole('status').filter({ hasText: 'Đã lưu CV riêng tư' })).toBeVisible();
    const writing = builder.locator('.writing-panel');
    await writing.getByRole('button', { name: 'Tạo đề xuất soạn CV', exact: true }).click();
    await openView(candidate, 'applications');
    await openView(candidate, 'cv-builder');
    await expect(writing.locator('.badge-ai-suggested')).toBeVisible({ timeout: 30000 });
    const accept = writing.getByRole('button', { name: 'Chấp nhận và đưa vào bản nháp', exact: true });
    await expect(accept).toBeEnabled({ timeout: 30000 });
    await expect(writing).toContainText('Kết quả mô phỏng kiểm thử.');
    const proposalSummary = await writing.getByRole('textbox', { name: 'Giới thiệu', exact: true }).inputValue();
    await accept.click();
    await expect(writing.locator('.badge-ai-accepted')).toBeVisible();
    await expect(writing.locator('.badge-ai-suggested')).toHaveCount(0);
    await expect(builder.locator('.builder-form').getByLabel('Giới thiệu', { exact: true })).toHaveValue(proposalSummary);
    await builder.getByRole('button', { name: 'Tạo bản xem trước PDF', exact: true }).click();
    await expect(builder.getByTitle('Xem trước CV PDF')).toBeVisible();
    await builder.getByRole('button', { name: 'Lưu thành phiên bản CV', exact: true }).click();
    await expect(builder.getByRole('status').filter({ hasText: 'Đã lưu CV riêng tư' })).toBeVisible();
    const resumes = await candidate.request.get('/api/resumes').then(response => response.json());
    expect(resumes).toHaveLength(1); expect(resumes[0].versions).toHaveLength(2);
    const version = resumes[0].versions[0];
    const original = await candidate.request.get(`/api/files/${version.fileId}`).then(response => response.body());
    expect(await candidate.request.get('/api/resumes/public/me').then(response => response.json())).toBeNull();
    await openView(candidate, 'jobs');
    await candidate.getByLabel('CV dùng để gợi ý việc', { exact: true }).selectOption(version.id);
    await candidate.getByRole('button', { name: 'Tìm việc theo CV', exact: true }).click();
    const baseline = candidate.locator('.job-discovery-results .matching-results');
    await expect(baseline).toContainText('retrieval_score');
    const admission = candidate.waitForResponse(response => new URL(response.url()).pathname === '/api/matching/recommendations' && response.request().method() === 'POST');
    await candidate.getByRole('button', { name: 'Gợi ý và phân tích tối đa 3 cặp', exact: true }).click();
    const admitted = await admission;
    expect(admitted.ok()).toBeTruthy();
    expect(admitted.request().postDataJSON()).toMatchObject({ direction: 'jobs', resumeVersionId: version.id, topK: 3 });
    const batch = await admitted.json(); expect(batch.selectedCount).toBeLessThanOrEqual(3);
    const results = candidate.getByRole('region', { name: 'Kết quả đối chiếu AI', exact: true });
    await expect(results.locator('.pair-result').first()).toContainText('Kết quả mô phỏng kiểm thử', { timeout: 30000 });
    await expect(candidate.locator('.job-discovery-controls .pair-result')).toHaveCount(0);
    // Reopen through ordinary UI after a full page reload; do not rewrite idempotency keys.
    await candidate.reload();
    await openView(candidate, 'jobs');
    await candidate.getByLabel('CV dùng để gợi ý việc', { exact: true }).selectOption(version.id);
    await candidate.getByRole('button', { name: 'Tìm việc theo CV', exact: true }).click();
    const historyRow = candidate.locator('.job-discovery-results .matching-results > li').filter({ hasText: title });
    let pairPosts = 0;
    candidate.on('request', request => {
      if (request.method() === 'POST' && ['/api/matching/pairs', '/api/matching/recommendations'].includes(new URL(request.url()).pathname)) pairPosts++;
    });
    const lookup = candidate.waitForResponse(response => new URL(response.url()).pathname === '/api/matching/pairs/latest');
    await historyRow.getByRole('button', { name: 'Xem kết quả đã lưu', exact: true }).click();
    const historical = await lookup;
    expect(historical.request().method()).toBe('GET');
    const stored = (await historical.json()).pair;
    expect(batch.items.map((item: { pairJobId: string }) => item.pairJobId)).toContain(stored.id);
    await expect(historyRow.locator('.pair-result')).toContainText('Kết quả mô phỏng kiểm thử');
    await expect(historyRow).toContainText('Xem lại không tạo yêu cầu AI mới.');
    await historyRow.locator('summary').filter({ hasText: 'Xem tiêu chí và bằng chứng' }).click();
    await historyRow.getByRole('button', { name: 'Tìm nguồn học cho tiêu chí này', exact: true }).first().click();
    await historyRow.getByRole('button', { name: 'Tìm tài liệu học', exact: true }).first().click();
    await expect(historyRow).toContainText('Search đang dùng mô phỏng local; chưa tìm kiếm web thật.');
    expect(pairPosts).toBe(0);
    await candidate.getByLabel('Từ khóa', { exact: true }).fill(title);
    await candidate.getByRole('button', { name: 'Tìm việc', exact: true }).click();
    const publicJob = candidate.locator('.job-list > .job-card').filter({ hasText: title });
    await publicJob.getByRole('button', { name: 'Nộp hồ sơ', exact: true }).click();
    await expect(candidate.getByText(`Đã nộp hồ sơ cho “${title}”.`, { exact: true })).toBeVisible();
    await openView(candidate, 'applications');
    await expect(candidate.locator('#applications')).toContainText(title);
    await openView(recruiter, 'recruiter-applicants');
    await job.getByRole('button', { name: /Hồ sơ ứng tuyển/ }).click();
    const link = await job.getByRole('link', { name: 'Mở CV đã nộp', exact: true }).getAttribute('href');
    const snapshot = await recruiterContext.request.get(link!);
    expect(snapshot.status()).toBe(200); expect(await snapshot.body()).toEqual(original);
    expect((await recruiterContext.request.get(`/api/files/${version.fileId}`)).status()).toBe(404);
    expect(await candidate.request.get('/api/resumes/public/me').then(response => response.json())).toBeNull();
  } finally { await candidateContext.close(); await recruiterContext.close(); }
});
